    movq %rsp, %rdi
    cld
    call _interrupt_handler

    popq %r15
    popq %r14
    popq %r13
    popq %r12
    popq %r11
    popq %r10
    popq %r9
    popq %r8
    popq %rbp
    popq %rdi
    popq %rsi
    popq %rdx
    popq %rcx
    popq %rbx
    popq %rax

    // check if returning to userspace
    testq $3, 24(%rsp)
    jz 2f
    swapgs
2:
    addq $16, %rsp
    iretq

